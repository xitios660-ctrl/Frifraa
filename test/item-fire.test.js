const test=require('node:test');
const assert=require('node:assert/strict');
const {spawnSync}=require('node:child_process');
test('fire burns exposed items, drops wait for fire to clear, chain fire and rematch remain authoritative',()=>{
 const script=`
 const assert=require('node:assert/strict');let time=100000;Date.now=()=>time;Math.random=()=>0;
 const {newRoom,tick,onMessage}=require('./server');const seen=[];
 const ws={playerId:'p',readyState:1,send(data){seen.push(JSON.parse(data));}};
 const r=newRoom('TESTA',ws,'Mary'),p=r.players.get('p');
 r.phase='playing';r.participantsAtStart=1;r.lastTick=time;
 r.board=Array.from({length:9},(_,y)=>Array.from({length:9},(_,x)=>!x||!y||x===8||y===8?1:0));
 r.board[3][4]=2;r.board[2][3]=1;
 r.powerups.set('3,3','shield');r.powerups.set('2,3','speed');r.powerups.set('3,1','bomb');
 r.bombs=[{x:3,y:3,range:3,ownerId:'p',explodeAt:time}];tick();
 assert.equal(r.powerups.has('3,3'),false);assert.equal(r.powerups.has('2,3'),false);assert.equal(r.powerups.has('3,1'),true);
 assert.equal(r.powerups.has('4,3'),false);assert.ok(r.pendingPowerups.some(i=>i.x===4&&i.y===3));
 assert.equal(r.effects.filter(e=>e.kind==='itemBurn').length,2);
 time+=400;r.flames.push({x:4,y:3,startedAt:time,expiresAt:time+500});tick();
 time+=101;tick();assert.equal(r.powerups.has('4,3'),false);
 time+=400;tick();assert.equal(r.powerups.has('4,3'),true);
 r.bombs=[{x:5,y:3,range:1,ownerId:'p',explodeAt:time}];tick();assert.equal(r.powerups.has('4,3'),false);
 r.powerups.set('1,1','bomb');r.flames.push({x:1,y:1,startedAt:time,expiresAt:time+500});tick();
 assert.equal(p.bombs,1,'cannot collect an item that is already burning');
 r.phase='finished';onMessage(ws,JSON.stringify({type:'start'}));
 assert.equal(r.pendingPowerups.length,0);assert.equal(r.collapse.index,0);assert.equal(r.collapse.startsAt,r.countdownUntil+90000);
 assert.equal(seen.at(-1).collapse.startsAt,r.collapse.startsAt);
 console.log('PASS');process.kill(process.pid,'SIGTERM');`;
 const child=spawnSync(process.execPath,['-e',script],{cwd:require('node:path').join(__dirname,'..'),env:{...process.env,PORT:'0'},encoding:'utf8',timeout:5000});
 assert.equal(child.status,0,child.stderr);assert.match(child.stdout,/PASS/);
});
